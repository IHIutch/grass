#!/usr/bin/env node
// Generate the fixed extend-heavy workload used by perf.sh.
// The output is deliberately assembled from integer loops and fixed strings;
// there is no timestamp, random value, host path, or platform-dependent input.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = fileURLToPath(new URL(".", import.meta.url));
const output = resolve(process.argv[2] || resolve(scriptDir, "extend-synth.scss"));
const placeholders = 120;
const extendsPerSide = 15;
const selectorPairs = placeholders / extendsPerSide;
const lines = [
  "// Generated by bench/fixtures/gen-extend-synth.mjs; do not edit.",
  "// Shape: 120 placeholders, 15 extends on each side of 8 descendant pairs.",
  "",
];

for (let i = 0; i < placeholders; i++) {
  lines.push(`%placeholder-${String(i).padStart(3, "0")} {`);
  lines.push(`  --extend-value-${String(i).padStart(3, "0")}: ${i};`);
  lines.push("}", "");
}

for (let pair = 0; pair < selectorPairs; pair++) {
  const start = pair * extendsPerSide;
  const selector = String(pair).padStart(2, "0");
  lines.push(`.extend-parent-${selector} {`);
  for (let i = start; i < start + extendsPerSide; i++) {
    lines.push(`  @extend %placeholder-${String(i).padStart(3, "0")};`);
  }
  lines.push(`  .extend-child-${selector} {`);
  for (let i = start; i < start + extendsPerSide; i++) {
    const childIndex = (i + extendsPerSide) % placeholders;
    lines.push(`    @extend %placeholder-${String(childIndex).padStart(3, "0")};`);
  }
  lines.push("  }", "}", "");
}

writeFileSync(output, lines.join("\n").replace(/\n+$/, "\n"), "utf8");
console.log(`Wrote ${output}`);
